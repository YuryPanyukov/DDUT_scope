def make_workbook(file_path: str, sheets: dict[str, Sequence[Sequence]]) -> str:
    """Создаёт Excel-файл: словарь «имя листа → строки»."""
    workbook = openpyxl.Workbook()
    workbook.remove(workbook.active)
    for sheet_name, rows in sheets.items():
        worksheet = workbook.create_sheet(title=sheet_name)
        for row in rows:
            worksheet.append(list(row))
    os.makedirs(os.path.dirname(os.path.abspath(file_path)), exist_ok=True)
    workbook.save(file_path)
    return file_path


def main(target_dir: str | None = None) -> int:
    """Создаёт тестовые файлы и шаблон, печатает результат."""
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    target = target_dir or os.path.join(root, "samples")
    os.makedirs(target, exist_ok=True)

    for file_name, sheets in SAMPLES.items():
        print(f"создан: {make_workbook(os.path.join(target, file_name), sheets)}")

    for file_name, sheets in MATRIX_SAMPLES.items():
        print(f"создан (лист-матрица): {make_workbook(os.path.join(target, file_name), sheets)}")

    template = ExcelExporter.create_template(
        os.path.join(target, "Шаблон_оценок.xlsx"),
        sheet_names=("Направление 1", "Направление 2"),
    )
    print(f"создан шаблон: {template}")
    return 0


